def get_monsters(category=None, min_challenge_rating=None, max_challenge_rating=None):
    """
    Retrieve monsters based on category and challenge rating range.

    :param category: The category of monsters to filter by (optional).
    :param min_challenge_rating: The minimum challenge rating (optional).
    :param max_challenge_rating: The maximum challenge rating (optional).
    :return: A list of monsters matching the criteria.
    """
    filtered_monsters = []

    if category:
        categories = [category] if category in monsters else []
    else:
        categories = monsters.keys()

    for cat in categories:
        for monster in monsters[cat]:
            if (min_challenge_rating is None or monster["challenge_rating"] >= min_challenge_rating) and \
               (max_challenge_rating is None or monster["challenge_rating"] <= max_challenge_rating):
                filtered_monsters.append(monster)

    return filtered_monsters
